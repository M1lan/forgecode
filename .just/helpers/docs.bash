#!/usr/bin/env bash
# docs.bash -- generate the fork's generated docs, and prove them current.
#
#   docs/justfile.md          FROM the Justfile (`just --dump`)
#   docs/fork-differences.md  FROM .fork.toml (the fork patch manifest)
#
#   docs.bash --write   regenerate both
#   docs.bash --check   exit 1 if either committed file has drifted
#
# WHY GENERATED, NOT WRITTEN
# Hand-written command docs rot the moment a recipe is renamed, and nothing
# catches it. The source of truth here is `just --dump --dump-format json`,
# which is the same machine contract the menu and doctor consume. --check runs
# inside `just ci`, so a recipe change that skips `just docs` fails the
# gate instead of shipping a lie.
#
# The fork-differences page follows the same rule for the fork's patch list:
# prose about the fork rotted at every upstream sync, so the facts live in
# .fork.toml and the page is rendered from it. taplo turns the TOML into JSON;
# jq does the rest, same as for the Justfile.
#
# Pure GNU Bash 5.3+.

# shellcheck source=tools.bash disable=SC2154,SC1091
source "$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd -P)/tools.bash"

set -uo pipefail

readonly MANIFEST_REL=".fork.toml"

# generated doc -> render function, in the order they are written and checked
readonly -a DOCS=(
  "docs/justfile.md" render_justfile
  "docs/fork-differences.md" render_fork
)

tools_need jq taplo || exit 1

# Render the whole document to stdout. Group order is taken from first
# appearance in the Justfile so the doc reads in the same order as the file.
render_justfile() {
  local json
  json=$(just_json) || just_die "just --dump failed"

  printf '# `just` reference\n\n'
  printf '<!-- GENERATED by .just/helpers/docs.bash -- do not edit by hand. -->\n'
  printf '<!-- Regenerate with `just docs`; `just docs-check` gates it in `just ci`. -->\n\n'
  printf 'Every recipe in the ForgeCode Justfile, grouped as the file groups them.\n'
  printf 'Machine-readable form: `just --dump --dump-format json`.\n\n'

  local -a groups
  mapfile -t groups < <(
    printf '%s' "$json" | jq -r '
      .recipes
      | to_entries[]
      | select(.value.private | not)
      | ([.value.attributes[]? | select(type == "object" and has("group")) | .group] | first) // "other"
    ' | awk '!seen[$0]++'
  )

  local g
  for g in "${groups[@]}"; do
    printf '## %s\n\n' "$g"
    printf '| recipe | arguments | what it does |\n'
    printf '|---|---|---|\n'
    # Separator is US (0x1f), not tab. `read` treats tab as IFS whitespace,
    # so consecutive tabs collapse into one and a recipe with no parameters
    # loses a field -- its doc slides into the arguments column.
    printf '%s' "$json" | jq -r --arg g "$g" '
      .recipes
      | to_entries[]
      | select(.value.private | not)
      | select((([.value.attributes[]? | select(type == "object" and has("group")) | .group] | first) // "other") == $g)
      | [
          .key,
          ([.value.parameters[]? | .name + (if .default then "=" + (.default | tostring) else "" end)] | join(" ")),
          ((.value.doc // "") | split("\n") | .[0] | gsub("\\|"; "\\\\|"))
        ]
      | join("\u001f")
    ' | LC_ALL=C sort | while IFS=$'\x1f' read -r name params doc; do
      printf '| `%s` | %s | %s |\n' "$name" "${params:-–}" "${doc:-–}"
    done
    printf '\n'
  done

  printf '## Dependencies\n\n'
  printf 'Recipes that run other recipes first.\n\n'
  printf '```\n'
  printf '%s' "$json" | jq -r '
    .recipes
    | to_entries[]
    | select(.value.dependencies | length > 0)
    | .key + " <- " + ([.value.dependencies[].recipe] | join(", "))
  ' | LC_ALL=C sort
  printf '```\n'
}

# Render docs/fork-differences.md from .fork.toml. Patch order is manifest
# order. Markdown fields (intent, details, doc.*) are emitted verbatim.
render_fork() {
  local json
  json=$(taplo get -f "$JUST_REPO_DIR/$MANIFEST_REL" -o json) ||
    just_die "cannot parse $MANIFEST_REL"

  printf '%s' "$json" | jq -r '
    def md: rtrimstr("\n");
    def code: "`" + . + "`";
    def or_none: if . == "" then "none" else . end;
    def link: if . == "" then "none" else "<" + . + ">" end;
    def cell: gsub("\\|"; "\\|");
    "# Fork differences: `\(.fork.work_branch)` vs upstream `\(.fork.mirror_branch)`",
    "",
    "<!-- GENERATED by .just/helpers/docs.bash from .fork.toml -- do not edit by hand. -->",
    "<!-- Regenerate with `just docs`; `just docs-check` gates it in `just ci`. -->",
    "",
    (.doc.intro | md),
    "",
    "| | |",
    "|---|---|",
    "| upstream | <\(.upstream.url)> (remote `\(.upstream.remote)`). \(.upstream.note) |",
    "| fork | `\(.origin.url)` (remote `\(.origin.remote)`) |",
    "| branches | mirror `\(.fork.mirror_branch)`, work `\(.fork.work_branch)` |",
    "| vcs, strategy | \(.fork.vcs), \(.fork.strategy) |",
    "| verify | quick `\(.verify.quick)`, full `\(.verify.full)` |",
    (.hosts | to_entries[] | "| host \(.key) | `\(.value.path)`. \(.value.note) |"),
    "",
    "## Patches",
    "",
    "| patch | what | conflict risk | upstream PR |",
    "|---|---|---|---|",
    (.patch[] | "| [`\(.id)`](#\(.id)) | \(.title | cell) | \(.conflict) | \(.upstream_pr | link) |"),
    "",
    (.patch[] |
      "## \(.id)",
      "",
      "**\(.title).** Conflict risk: \(.conflict).",
      "",
      (.intent | md),
      "",
      (if (.details // "") != "" then (.details | md), "" else empty end),
      "| | |",
      "|---|---|",
      "| files | \([.files[] | code] | join(", ")) |",
      "| drop when | \(.drop_when | cell) |",
      "| upstream PR | \(.upstream_pr | link) |",
      "| upstream issue | \(.upstream_issue | link) |",
      "| re-read after a sync | \([.docs[] | code] | join(", ") | or_none) |",
      ""
    ),
    "## Reproducing the comparison",
    "",
    "Compare against `\(.upstream.remote)/\(.fork.mirror_branch)` explicitly; the local `\(.fork.mirror_branch)` is only as current as the last sync.",
    "",
    "```bash",
    "git fetch \(.upstream.remote)",
    "git log  --oneline --no-merges \(.upstream.remote)/\(.fork.mirror_branch)..\(.fork.work_branch)   # fork-only commits",
    "git log  --oneline \(.fork.work_branch)..\(.upstream.remote)/\(.fork.mirror_branch)               # upstream not yet merged",
    "git cherry -v \(.upstream.remote)/\(.fork.mirror_branch) \(.fork.work_branch)                     # \"-\" = absorbed upstream",
    "git diff --stat $(git merge-base \(.upstream.remote)/\(.fork.mirror_branch) \(.fork.work_branch))..\(.fork.work_branch)",
    "```",
    "",
    "## Branch policy",
    "",
    (.doc.branch_policy | md)
  '
}

case "${1:---check}" in
  --write)
    mkdir -p "$JUST_REPO_DIR/docs" || exit 1
    for ((i = 0; i < ${#DOCS[@]}; i += 2)); do
      rel=${DOCS[i]} path=$JUST_REPO_DIR/${DOCS[i]}
      "${DOCS[i + 1]}" > "$path.tmp" || {
        rm -f -- "$path.tmp"
        just_die "render failed: $rel"
      }
      mv -f -- "$path.tmp" "$path"
      printf 'wrote %s\n' "$rel"
    done
    ;;
  --check)
    drifted=0
    for ((i = 0; i < ${#DOCS[@]}; i += 2)); do
      rel=${DOCS[i]} path=$JUST_REPO_DIR/${DOCS[i]}
      if [[ ! -f $path ]]; then
        printf '%s is missing -- run: just docs\n' "$rel" >&2
        drifted=1
        continue
      fi
      if diff -u "$path" <("${DOCS[i + 1]}") > /dev/null 2>&1; then
        printf '%s is current\n' "$rel"
        continue
      fi
      printf '%s has drifted from its source:\n\n' "$rel" >&2
      diff -u "$path" <("${DOCS[i + 1]}") | head -40 >&2
      drifted=1
    done
    ((drifted)) && printf '\nfix with: just docs\n' >&2
    exit "$drifted"
    ;;
  *)
    printf 'usage: docs.bash {--write | --check}\n' >&2
    exit 2
    ;;
esac
